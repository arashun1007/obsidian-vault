def build():
    species = []
    for cat, rows in DATA.items():
        clabel, color, dhab = CATEGORIES[cat]
        for r in rows:
            (fid, name, kana, sci, fam, season, size, dist, taste, cook, alias, note) = r
            if not name:
                continue  # skip placeholder rows
            species.append({
                "id": fid,
                "name": name,
                "kana": kana,
                "scientificName": sci,
                "family": fam,
                "category": cat,
                "categoryLabel": clabel,
                "accentColor": color,
                "seasonMonths": season,
                "typicalSizeCm": size,
                "distribution": dist,
                "habitat": dhab,
                "taste": taste,
                "cookingMethods": cook,
                "aliases": alias,
                "description": note,
                # image hook: filled in later by image2 pipeline
                "imageAsset": None,
            })
    species.sort(key=lambda s: (list(CATEGORIES).index(s["category"]), s["kana"]))
    return {
        "schemaVersion": 1,
        "generatedNote": "実データに基づく日本の市場魚介データセット。imageAsset は image2 で後日付与。",
        "categories": [
            {"key": k, "label": v[0], "accentColor": v[1]} for k, v in CATEGORIES.items()
        ],
        "species": species,
    }

if __name__ == "__main__":
    out = build()
    here = os.path.dirname(os.path.abspath(__file__))
    # write to app assets
    target = os.environ.get("FISH_OUT", os.path.join(here, "fish.json"))
    with open(target, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=2)
    n = len(out["species"])
    by = {}
    for s in out["species"]:
        by[s["categoryLabel"]] = by.get(s["categoryLabel"], 0) + 1
    print(f"wrote {n} species to {target}")
    for k, v in by.items():
        print(f"  {k}: {v}")
